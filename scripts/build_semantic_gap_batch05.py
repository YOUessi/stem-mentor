def build():
    ids = [item["id"] for item in LESSONS]
    if len(ids) != len(set(ids)):
        raise ValueError("duplicate semantic-gap lesson IDs")
    # Deliberately require one explicit source lesson for every known editorial gap,
    # but never assert pedagogical completion or authentic teacher approval.
    gaps = json.loads((ROOT/"knowledge/deep/semantic_gaps_batch04.json").read_text(encoding="utf-8"))["gaps"]
    expected = {row["recommended_lesson_id"]:row["curriculum_id"] for row in gaps}
    actual = {item["id"]:item["curriculum_ids"][0] for item in LESSONS}
    if expected != actual:
        raise ValueError(f"batch05 editorial gap mismatch: missing={sorted(set(expected)-set(actual))}, extra={sorted(set(actual)-set(expected))}")
    return LESSONS

def main():
    parser = argparse.ArgumentParser(description="Reproduce the 23 editorial subskill drafts")
    parser.add_argument("--check", action="store_true", help="Compare frozen source without writing")
    args = parser.parse_args()
    content = json.dumps(build(),ensure_ascii=False,indent=2)+"\n"
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit("FAIL: batch05 deep lesson JSON differs from project-authored source")
        print(f"PASS: {len(LESSONS)} independently authored gap drafts match frozen JSON; 0 teacher-approved")
        return
    OUTPUT.parent.mkdir(parents=True,exist_ok=True)
    OUTPUT.write_text(content,encoding="utf-8")
    print(f"WROTE {OUTPUT}, {len(LESSONS)} content drafts; never teacher-approved")

if __name__ == "__main__":
    main()
