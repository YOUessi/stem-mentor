def example(question, step_1, step_2, answer, check):
    return {"question":question, "steps":[step_1,step_2],
            "answer":answer,"check":check}

def negative(false_claim, case, explanation):
    return {"false_claim":false_claim, "example":case,
            "explanation":explanation}

def add(*, key, topic, kind, title, formula, notation, prerequisites, assumptions,
        steps, boundaries, counterexample, first, second, misconception,
        hints, near, far, dependencies=()):
    """Explicit content; no hallucinated review, no generic proof fillers."""
    assert len(steps) >= (3 if kind in ("theorem", "method") else 2)
    assert len(hints) in (3,4)
    obj = {
      "id":key, "curriculum_ids":[topic], "kind":kind, "title":title,
      "version":"1.0.0","notation":notation,"prerequisites":prerequisites,
      "prerequisite_lesson_ids":list(dependencies),
      "definition":formula if kind=="concept" else None,
      "statement":formula if kind!="concept" else None,
      "assumptions":assumptions,
      "proof_steps":[{"claim":c,"reason":r} for c,r in steps] if kind=="theorem" else [],
      "rationale_steps":steps if kind!="theorem" else [],
      "boundaries":boundaries,"counterexamples":[negative(*counterexample)],
      "worked_examples":[example(*first),example(*second)],
      "misconceptions":[{
         "error":misconception[0],
         "why_wrong":misconception[1],
         "repair_question":misconception[2]}],
      "hint_ladder":hints,
      "transfer":{"near":near,"far":far},
      "provenance":{"kind":"PROJECT_AUTHORED","permission":"PROJECT_AUTHORED",
           "curriculum_standard":STANDARD, "standard_url":SOURCE,
           "author_role":"PROJECT_AUTHOR"},
      "review":{"status":"REVIEW_PENDING","reviewer_id":None,
           "reviewed_at":None,"review_record":None},
      "teacher_solution_visibility":"TEACHER_ONLY",
    }
    assert key.startswith("math.hs.")
    LESSONS.append(obj)

